<?php

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}


/*
|--------------------------------------------------------------------------
| آدرس برگشت
|--------------------------------------------------------------------------
*/

$redirect = $_GET['redirect'] ?? '/Kavian/';


/*
|--------------------------------------------------------------------------
| جلوگیری از Redirect به سایت خارجی
|--------------------------------------------------------------------------
*/

if (
    empty($redirect) ||
    stripos($redirect, '/Kavian/') !== 0
) {
    $redirect = '/Kavian/';
}


/*
|--------------------------------------------------------------------------
| پاک کردن تمام اطلاعات Session
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| حذف Cookie مربوط به Session
|--------------------------------------------------------------------------
*/

if (ini_get('session.use_cookies')) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params['path'],
        $params['domain'],
        $params['secure'],
        $params['httponly']
    );
}


/*
|--------------------------------------------------------------------------
| نابود کردن Session
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| برگشت به همان صفحه
|--------------------------------------------------------------------------
*/

header(
    'Location: ' . $redirect
);

exit;